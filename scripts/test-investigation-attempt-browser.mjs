import process from "node:process";
import assert from "node:assert/strict";
import { createServer } from "vite";
import { mkdir } from "node:fs/promises";
import { CASES } from "../src/data/cases.js";

const { chromium } = await import(process.env.CYBERTRACE_PLAYWRIGHT_MODULE || "playwright");
const server = await createServer({ server: { host: "127.0.0.1", port: 0 }, logLevel: "silent" });
const out = process.env.CYBERTRACE_ATTEMPT_ARTIFACTS || "/tmp/cybertrace-attempt-browser";
await mkdir(out, { recursive: true });
let browser;
try {
  await server.listen();
  const origin = "http://127.0.0.1:" + server.httpServer.address().port;
  const url = origin + "/tests/fixtures/investigation-attempt.html";
  browser = await chromium.launch({ executablePath: process.env.CYBERTRACE_CHROMIUM_PATH || undefined, headless: true, args: ["--no-sandbox"] });
  const first = CASES[0], correct = first.evidenceOptions.find(item => item.correct), wrong = first.evidenceOptions.find(item => !item.correct);
  const partial = first.decisions.find(item => item.points === 20);
  for (const width of [320, 390, 1440]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, reducedMotion: "reduce" });
    const errors = [], external = [];
    await context.route("**/*", route => {
      if (new URL(route.request().url()).origin === origin) return route.continue();
      external.push(new URL(route.request().url()).hostname);
      return route.abort("blockedbyclient");
    });
    const page = await context.newPage();
    page.setDefaultTimeout(15000);
    page.on("pageerror", error => errors.push(error.message));
    const step = number => page.locator('.inv-progress-step[aria-current="step"]').filter({ hasText: number });
    const start = async () => { await page.getByRole("button", { name: /ابدأ التحليل/ }).click(); await page.locator("#evidence-task").waitFor(); };
    const inspect = () => page.evaluate(() => window.__attemptFixture.inspect());
    await page.goto(url + (width === 320 ? "?text=xlarge" : ""));
    await start();
    assert((await page.locator("#evidence-task").boundingBox()).y < 600, "beginner task is visible before the optional workspace");
    assert.equal(await page.locator(".inv-workspace-disclosure").evaluate(node => node.open), false);
    assert.equal(await page.getByRole("region", { name: "السجل الأساسي للتحقيق" }).locator(".inv-log-line").count(), first.logLines.length);
    await page.locator(".inv-workspace-disclosure summary").click();
    await page.locator("#iw-notes").fill("دفتر محلي محفوظ عبر تحديث المحاولة وتبديل الحساب");
    await page.locator(".inv-workspace-disclosure summary").click();
    await page.getByRole("button", { name: wrong.label, exact: true }).click();
    await page.getByRole("button", { name: /تأكيد الاختيار/ }).click();
    const evidenceOrder = await page.locator(".inv-options button").allTextContents();
    await page.reload();
    await step("02").waitFor();
    assert.equal(await page.getByRole("button", { name: wrong.label, exact: true }).getAttribute("aria-pressed"), "true");
    assert.deepEqual(await page.locator(".inv-options button").allTextContents(), evidenceOrder);
    assert((await page.locator(".inv-accuracy").innerText()).includes("90/100"));
    await page.locator(".inv-workspace-disclosure summary").click();
    assert.equal(await page.locator("#iw-notes").inputValue(), "دفتر محلي محفوظ عبر تحديث المحاولة وتبديل الحساب");
    await page.locator(".inv-workspace-disclosure summary").click();
    await page.getByRole("button", { name: correct.label, exact: true }).click();
    await page.getByRole("button", { name: /تأكيد الاختيار/ }).click();
    await page.getByRole("button", { name: /المتابعة إلى القرار/ }).click();
    await page.getByRole("button", { name: partial.label, exact: true }).click();
    const decisionOrder = await page.locator(".inv-options button").allTextContents();
    await page.reload();
    await step("03").waitFor();
    assert.equal(await page.getByRole("button", { name: partial.label, exact: true }).getAttribute("aria-pressed"), "true");
    assert.deepEqual(await page.locator(".inv-options button").allTextContents(), decisionOrder);
    assert.equal((await inspect()).xp, 0);
    assert.deepEqual((await inspect()).calls, []);
    await page.evaluate(() => window.__attemptFixture.setOwner("another-local-owner"));
    await step("01").waitFor();
    await start();
    await page.locator(".inv-workspace-disclosure summary").click();
    assert.equal(await page.locator("#iw-notes").inputValue(), "");
    await page.evaluate(() => window.__attemptFixture.setOwner(null));
    await step("03").waitFor();
    assert.equal(await page.getByRole("button", { name: partial.label, exact: true }).getAttribute("aria-pressed"), "true");
    await page.evaluate(id => window.__attemptFixture.setCase(id), CASES[1].id);
    await step("01").waitFor();
    await page.evaluate(id => window.__attemptFixture.setCase(id), first.id);
    await step("03").waitFor();
    await page.screenshot({ path: out + "/restored-decision-" + width + ".png" });
    // Two immediate clicks use the real completion handler. The ref prevents
    // an award or bridge call from being repeated before React commits.
    await page.getByRole("button", { name: /تنفيذ القرار/ }).evaluate(button => { button.click(); button.click(); });
    await step("04").waitFor();
    const result = await inspect();
    assert.equal(result.xp, 50);
    assert.equal(result.results[first.id].attempts, 1);
    assert.equal(result.results[first.id].lastScore, 50);
    assert.equal(result.calls.length, 1);
    assert.equal(await page.evaluate(key => localStorage.getItem(key), result.pendingKey), null);
    await page.reload();
    await step("01").waitFor();
    assert.equal((await inspect()).xp, 50, "refresh after completion does not award points");
    assert.equal((await inspect()).results[first.id].attempts, 1);
    assert.equal((await inspect()).calls.length, 1);
    await start();
    await page.getByRole("button", { name: wrong.label, exact: true }).click();
    page.once("dialog", dialog => dialog.accept());
    await page.getByRole("button", { name: "بدء محاولة جديدة", exact: true }).click();
    await step("01").waitFor();
    await page.reload();
    await step("01").waitFor();
    await start();
    assert.equal(await page.locator('.inv-options [aria-pressed="true"]').count(), 0);
    assert((await page.locator(".inv-accuracy").innerText()).includes("100/100"));
    await page.screenshot({ path: out + "/beginner-task-" + width + ".png" });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.deepEqual(errors, []);
    assert.deepEqual(external, []);
    console.log("PASS investigation attempt " + width + "px: evidence/decision reload, scope isolation, notebook preservation, no duplicate completion, restart and visible beginner objective");
    await context.close();
  }
  const unavailable = await browser.newContext({ viewport: { width: 390, height: 844 } });
  await unavailable.route("**/*", route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort("blockedbyclient"));
  await unavailable.addInitScript(() => {
    const save = Storage.prototype.setItem;
    Storage.prototype.setItem = function(key, value) {
      if (key.startsWith("cybertrace_pending_attempt:")) throw new DOMException("Quota exceeded", "QuotaExceededError");
      return save.call(this, key, value);
    };
  });
  const page = await unavailable.newPage();
  await page.goto(url);
  await page.getByRole("button", { name: /ابدأ التحليل/ }).click();
  await page.getByRole("button", { name: correct.label, exact: true }).click();
  assert.match(await page.locator(".inv-attempt-status").innerText(), /تعذّر حفظ المحاولة/);
  await page.getByRole("button", { name: /تأكيد الاختيار/ }).click();
  await page.getByRole("button", { name: /المتابعة إلى القرار/ }).click();
  assert.equal(await page.locator('.inv-progress-step[aria-current="step"]').innerText(), "03\nالقرار");
  console.log("PASS unavailable draft storage: usable session with explicit save warning");
  await unavailable.close();
} finally {
  if (browser) await browser.close();
  await server.close();
}
